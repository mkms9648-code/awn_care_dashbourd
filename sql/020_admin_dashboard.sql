-- ----------------------------------------------------------------------------
-- 1) سجل تنفيذات الفلو — الحلقة الناقصة بين n8n_chat_histories وبين n8n نفسه
-- ----------------------------------------------------------------------------
-- كل توّرن (turn) ناجح من الـ AI Agent بيسجّل هنا صف واحد بمعرّف التنفيذ
-- (execution) بتاعه في n8n. بيتسجّل من نفس الـ workflow، بعد ما الأجنت يرد
-- وقبل الرد للطبيب — لو الإدراج فشل الرد للطبيب لازم يكمل عادي (onError على
-- مستوى العقدة في n8n، مش هنا).

create table if not exists public.flow_execution_log (
  id               bigint generated by default as identity,
  workspace_id     uuid,
  org_id           uuid,
  staff_id         uuid,
  bot_key          text not null,
  chat_id          text not null,
  session_id       text not null,   -- نفس مفتاح n8n_chat_histories: chat_id || '-' || bot_key
  n8n_execution_id text not null,
  n8n_workflow_id  text not null,
  occurred_at      timestamptz not null default now(),
  constraint flow_execution_log_pkey primary key (id),
  constraint flow_execution_log_workspace_id_fkey foreign key (workspace_id) references public.workspaces(id),
  constraint flow_execution_log_org_id_fkey       foreign key (org_id)       references public.orgs(id),
  constraint flow_execution_log_staff_id_fkey      foreign key (staff_id)     references public.staff(id)
);

create index if not exists ix_flow_execution_log_session
  on public.flow_execution_log (session_id, occurred_at);

create index if not exists ix_flow_execution_log_workspace
  on public.flow_execution_log (workspace_id, occurred_at);

-- دالة التسجيل نفسها — بتتنادى من n8n بنفس أسلوب أي app_* تاني (add_orders،
-- prescribe، ...): بتاخد (platform, bot_key, chat_id) الخام وتعيد اشتقاق
-- الهوية عن طريق app_bind، مش بتاخد staff_id/workspace_id جاهزين من n8n.
create or replace function public.app_log_flow_execution(
  p_platform text, p_bot_key text, p_chat_id text,
  p_execution_id text, p_workflow_id text
)
returns void
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
declare
  c app_ctx;
begin
  c := app_bind(p_platform, p_bot_key, p_chat_id, false); -- بدون touch، الـ Resolve Staff في أول الفلو عمل ده أصلًا

  insert into flow_execution_log
    (workspace_id, org_id, staff_id, bot_key, chat_id, session_id, n8n_execution_id, n8n_workflow_id)
  values
    (c.workspace_id, c.org_id, c.staff_id, p_bot_key, p_chat_id,
     p_chat_id || '-' || p_bot_key, p_execution_id, p_workflow_id);
end;
$$;

grant execute on function public.app_log_flow_execution(text, text, text, text, text) to anon;

-- ----------------------------------------------------------------------------
-- 2) هوية المدير — allow-list منفصلة عن جدول staff (اللي هو للأطباء)
-- ----------------------------------------------------------------------------

create table if not exists public.app_admins (
  id         uuid not null references auth.users(id) on delete cascade,
  email      text not null,
  role       text not null default 'admin' check (role = any(array['owner','admin'])),
  created_at timestamptz not null default now(),
  constraint app_admins_pkey primary key (id)
);

alter table public.app_admins enable row level security;

drop policy if exists app_admins_self_select on public.app_admins;
create policy app_admins_self_select on public.app_admins
  for select using (id = auth.uid());

create or replace function public.app_is_admin()
returns boolean
language sql
stable
security definer
set search_path to 'public', 'pg_temp'
as $$
  select exists (select 1 from public.app_admins where id = auth.uid());
$$;

grant execute on function public.app_is_admin() to authenticated;

