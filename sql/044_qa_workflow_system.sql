create or replace function public.admin_qa_update_flag_analysis(
  p_flag_id           text,
  p_severity          text default null,
  p_category          text default null,
  p_scenario          text default null,
  p_expected_behavior text default null,
  p_actual_behavior   text default null,
  p_confidence        numeric default null
)
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
declare v_test_run_id text;
begin
  if not app_is_admin() then
    raise exception 'AWN_FORBIDDEN: للإداريين فقط.';
  end if;

  update qa_test_flags
     set severity          = coalesce(p_severity, severity),
         category          = coalesce(p_category, category),
         scenario          = coalesce(p_scenario, scenario),
         expected_behavior = coalesce(p_expected_behavior, expected_behavior),
         actual_behavior   = coalesce(p_actual_behavior, actual_behavior),
         confidence        = coalesce(p_confidence, confidence),
         status            = 'analyzed'
   where flag_id = p_flag_id
  returning test_run_id into v_test_run_id;

  if v_test_run_id is null then
    raise exception 'AWN_NOT_FOUND: ملاحظة مش موجودة: %', p_flag_id;
  end if;

  update qa_test_runs r
     set critical_flags = (select count(*) from qa_test_flags where test_run_id = v_test_run_id and severity = 'critical'),
         major_flags    = (select count(*) from qa_test_flags where test_run_id = v_test_run_id and severity = 'major'),
         minor_flags    = (select count(*) from qa_test_flags where test_run_id = v_test_run_id and severity = 'minor')
   where r.test_run_id = v_test_run_id;

  return jsonb_build_object('flag_id', p_flag_id);
end;
$$;
grant execute on function public.admin_qa_update_flag_analysis(text, text, text, text, text, text, numeric) to authenticated;

