-- ----------------------------------------------------------------------------
-- 5) ربط تنفيذات n8n الحقيقية بالرسايل — دليل مش تخمين
-- ----------------------------------------------------------------------------
-- خطوتين:
--  أ) وسم أي رسالة بوت فيها نص الفشل الثابت (Agent Error Fallback) كـ
--     is_agent_error — ده دليل مؤكد 100% (مطابقة نص حرفي)، مش استنتاج.
--  ب) ربط باقي رسايل البوت (الناجحة بس) بصفوف flow_execution_log الحقيقية
--     في نفس النافذة الزمنية للتشغيلة، بالترتيب — لأن Log Execution بيتسجل
--     فقط عند نجاح الـ AI Agent، فعدد صفوف اللوج المفروض يساوي عدد رسايل
--     البوت الناجحة بالظبط.
create or replace function public.admin_qa_correlate_executions(p_test_run_id text)
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
declare
  v_run                 qa_test_runs%rowtype;
  v_session_id          text;
  v_updated             integer := 0;
  v_agent_error_marked  integer := 0;
begin
  if not app_is_admin() then
    raise exception 'AWN_FORBIDDEN: للإداريين فقط.';
  end if;

  select * into v_run from qa_test_runs where test_run_id = p_test_run_id;
  if not found then
    raise exception 'AWN_NOT_FOUND: اختبار مش موجود: %', p_test_run_id;
  end if;
  if v_run.test_chat_id is null then
    return jsonb_build_object('updated', 0, 'agent_errors_marked', 0, 'reason', 'no_chat_id');
  end if;

  v_session_id := v_run.test_chat_id || '-' || v_run.bot_key;

  update qa_test_messages
     set is_agent_error = true
   where test_run_id = p_test_run_id
     and role = 'bot'
     and content ilike '%something went wrong on my end%';
  get diagnostics v_agent_error_marked = row_count;

  with ordered_msgs as (
    select id, row_number() over (order by turn_no) as rn
      from qa_test_messages
     where test_run_id = p_test_run_id
       and role = 'bot'
       and is_agent_error = false
  ),
  ordered_logs as (
    select n8n_execution_id, n8n_workflow_id,
           row_number() over (order by occurred_at, id) as rn
      from flow_execution_log
     where session_id = v_session_id
       and occurred_at >= v_run.started_at
       and occurred_at <= coalesce(v_run.ended_at, now()) + interval '2 minutes'
  )
  update qa_test_messages m
     set n8n_execution_id = l.n8n_execution_id,
         n8n_workflow_id  = l.n8n_workflow_id
    from ordered_msgs om
    join ordered_logs l on l.rn = om.rn
   where m.id = om.id;
  get diagnostics v_updated = row_count;

  update qa_test_runs r
     set n8n_workflow_id = (
       select m.n8n_workflow_id from qa_test_messages m
        where m.test_run_id = r.test_run_id and m.n8n_workflow_id is not null
        limit 1
     )
   where r.test_run_id = p_test_run_id;

  return jsonb_build_object('updated', v_updated, 'agent_errors_marked', v_agent_error_marked);
end;
$$;
grant execute on function public.admin_qa_correlate_executions(text) to authenticated;

