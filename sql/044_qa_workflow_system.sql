create or replace function public.admin_qa_get_test_run(p_test_run_id text)
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
declare
  v_run jsonb;
begin
  if not app_is_admin() then
    raise exception 'AWN_FORBIDDEN: للإداريين فقط.';
  end if;

  select to_jsonb(r) || jsonb_build_object(
           'test_doctor_name', s.full_name,
           'workspace_name', w.name,
           'org_name', o.name
         )
    into v_run
    from qa_test_runs r
    left join staff s on s.id = r.test_staff_id
    left join workspaces w on w.id = r.workspace_id
    left join orgs o on o.id = w.org_id
   where r.test_run_id = p_test_run_id;

  if v_run is null then
    raise exception 'AWN_NOT_FOUND: اختبار مش موجود: %', p_test_run_id;
  end if;

  return v_run || jsonb_build_object(
    'messages', coalesce((
      select jsonb_agg(to_jsonb(m) order by m.turn_no, m.id)
        from qa_test_messages m where m.test_run_id = p_test_run_id
    ), '[]'::jsonb),
    'flags', coalesce((
      select jsonb_agg(
               to_jsonb(f) || jsonb_build_object(
                 'root_cause', (
                   select to_jsonb(rc) from qa_root_cause_analyses rc
                    where rc.flag_id = f.flag_id
                    order by rc.analyzed_at desc limit 1
                 )
               ) order by f.created_at
             )
        from qa_test_flags f where f.test_run_id = p_test_run_id
    ), '[]'::jsonb)
  );
end;
$$;
grant execute on function public.admin_qa_get_test_run(text) to authenticated;

